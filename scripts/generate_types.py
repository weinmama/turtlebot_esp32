"""Generate only the required Pico-ROS types from installed ROS type descriptions.

Run with a sourced ROS installation: python3 scripts/generate_types.py
"""
import json
from pathlib import Path
from ament_index_python.packages import get_package_share_directory

ROOT = Path(__file__).resolve().parents[1]
TOPICS = ["geometry_msgs/msg/TwistStamped", "nav_msgs/msg/Odometry",
          "sensor_msgs/msg/Imu", "std_msgs/msg/Float32MultiArray",
          "rcl_interfaces/msg/Log", "std_msgs/msg/String", "std_msgs/msg/Int64MultiArray"]
BASE = {1: None, 2: "int8_t", 3: "uint8_t", 4: "int16_t", 5: "uint16_t",
        6: "int32_t", 7: "uint32_t", 8: "int64_t", 9: "uint64_t",
        10: "float", 11: "double", 13: "char", 15: "bool", 16: "uint8_t", 17: "rstring"}
types, hashes = {}, {}
for name in TOPICS:
    package, kind, short = name.split("/")
    doc = json.loads((Path(get_package_share_directory(package)) / kind / (short + ".json")).read_text())
    desc = doc["type_description_msg"]
    for item in [desc["type_description"], *desc["referenced_type_descriptions"]]:
        types[item["type_name"]] = item
    hashes.update((item["type_name"], item["hash_string"].removeprefix("RIHS01_")) for item in doc["type_hashes"])

def cname(name):
    return "ros_" + name.rsplit("/", 1)[1]

lines, done = [], set()
def emit(name):
    if name in done:
        return
    item = types[name]
    for field in item["fields"]:
        nested = field["type"]["nested_type_name"]
        if nested:
            emit(nested)
    done.add(name)
    package, kind, short = name.split("/")
    lines.extend([f'    CTYPE({cname(name)}, "{package}::{kind}::dds_::{short}",',
                  f'        "{hashes[name]}",'])
    for field in item["fields"]:
        typ = field["type"]
        ident = typ["type_id"]
        base = ident % 48
        ctype = cname(typ["nested_type_name"]) if base == 1 else BASE[base]
        macro = "FIELD" if ident < 48 else "ARRAY" if ident < 96 else "SEQUENCE"
        capacity = f', {typ["capacity"]}' if macro == "ARRAY" else ""
        lines.append(f'        {macro}({ctype}, {field["name"]}{capacity})')
    lines.append("    )")

for name in TOPICS:
    emit(name)
text = "// Generated by scripts/generate_types.py from ROS type descriptions.\n#pragma once\n\n"
text += "#define MSG_LIST(BTYPE, CTYPE, TTYPE, FIELD, ARRAY, SEQUENCE) \\\n"
text += " \\\n".join(lines) + "\n\n#define SRV_LIST(SRV, REQUEST, REPLY, FIELD, ARRAY, SEQUENCE)\n"
(ROOT / "include/robot_types.h").write_text(text)
